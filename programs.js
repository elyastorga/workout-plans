// Descanso sugerido según rango de reps (segundos)
function suggestedRest(reps) {
  const lo = parseInt(reps, 10);
  if (isNaN(lo)) return 60;
  if (lo <= 5) return 180;
  if (lo <= 8) return 150;
  if (lo <= 10) return 120;
  return 90;
}
